def detect_targets(project: Path) -> dict[str, str]:
    """Target -> where it was detected ('project' or 'home')."""
    out: dict[str, str] = {}
    for t, markers in TARGET_PROJECT_MARKERS.items():
        if any((project / m).exists() for m in markers):
            out[t] = "project"
        elif TARGET_HOME_DIRS[t].is_dir():
            out[t] = "home"
    return out


def choose_targets(project: Path, requested: str | None) -> list[str]:
    if requested and requested != "auto":
        wanted = [t.strip() for t in requested.split(",") if t.strip()]
        for t in wanted:
            if t not in TARGETS and t != "all":
                raise SystemExit(f"unknown target: {t} (choose from {', '.join(TARGETS)}, all, auto)")
        if "all" in wanted:
            return list(TARGETS)
        return [t for t in TARGETS if t in wanted] + (["generic"] if "generic" not in wanted else [])
    found = list(detect_targets(project).keys())
    return [t for t in TARGETS if t in found] + ["generic"]


