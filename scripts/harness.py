def yaml_unsafe(text: str) -> list[str]:
    bad = []
    if not text.startswith("---"):
        return bad
    for line in text.split("\n")[1:]:
        if line.strip() == "---":
            break
        m = re.match(r"^([A-Za-z0-9_\-]+):\s+(.*)$", line)
        if not m:
            continue
        v = m.group(2)
        if v.startswith(('"', "'", "[", ">", "|")):
            continue
        if ": " in v or " #" in v:
            bad.append(m.group(1))
    return bad


def cmd_lint(ctx: Ctx, args) -> int:
    errors, warnings = [], []
    lib = library_agents(include_retired=True)
    reg = load_models()
    age = registry_age_days(reg)
    if age is None:
        warnings.append("library/models.json: no checked date; run `harness models touch` after verifying it")
    elif age > as_int(reg.get("max_age_days"), 14):
        warnings.append(f"library/models.json: checked {reg.get('checked')}, {age} days ago; refresh per references/models.md")
    for name, (p, fm, body) in lib.items():
        for k in ("name", "title", "version", "tier", "description", "tags", "status"):
            if fm.get(k) in ("", None):
                errors.append(f"library/{p.name}: missing {k}")
        if fm.get("name") != p.stem:
            errors.append(f"library/{p.name}: name `{fm.get('name')}` differs from file name")
        if as_int(fm.get("tier"), -1) not in (0, 1, 2, 3):
            errors.append(f"library/{p.name}: tier must be 0-3")
        for sp in as_list(fm.get("spawns")):
            if sp != "*" and sp not in lib:
                warnings.append(f"library/{p.name}: spawns `{sp}` which is not a library agent")
        bad = yaml_unsafe(p.read_text(encoding="utf-8"))
        if bad:
            if args.fix:
                write_note(p, fm, body)
                warnings.append(f"library/{p.name}: quoted {', '.join(bad)} for strict YAML")
            else:
                errors.append(f"library/{p.name}: {', '.join(bad)} contain ': ' unquoted (strict YAML would reject); run lint --fix")
    if ctx.exists():
        inst = ctx.instances()
        for name, (p, fm, body) in inst.items():
            if fm.get("name") != p.stem:
                errors.append(f"harness/agents/{p.name}: name `{fm.get('name')}` differs from file name")
            if not slug_ok(name):
                errors.append(f"harness/agents/{p.name}: `{name}` is not a valid agent name")
            libname = fm.get("library") or ""
            if libname and libname not in lib:
                errors.append(f"harness/agents/{p.name}: library agent `{libname}` not found")
            if libname and libname in lib and as_int(lib[libname][1].get("version"), 1) > as_int(fm.get("library_version"), 0):
                warnings.append(f"harness/agents/{p.name}: library `{libname}` is at v{lib[libname][1].get('version')}; recompile")
            if not libname and fm.get("status") in ("active", "draft"):
                if not get_section(body, "Charter").strip() or "Write the charter here" in get_section(body, "Charter"):
                    errors.append(f"harness/agents/{p.name}: local draft without a charter")
                if not fm.get("description"):
                    warnings.append(f"harness/agents/{p.name}: local draft without a description (matching and delegation use it)")
            if fm.get("status") in ("active", "draft"):
                cpath = ctx.compiled_generic / f"{name}.md"
                if not cpath.exists():
                    warnings.append(f"harness/agents/{p.name}: not compiled")
                elif cpath.stat().st_mtime < p.stat().st_mtime:
                    warnings.append(f"harness/agents/{p.name}: changed after last compile")
            bad = yaml_unsafe(p.read_text(encoding="utf-8"))
            if bad:
                if args.fix:
                    write_note(p, fm, body)
                    warnings.append(f"harness/agents/{p.name}: quoted {', '.join(bad)} for strict YAML")
                else:
                    errors.append(f"harness/agents/{p.name}: {', '.join(bad)} contain ': ' unquoted; run lint --fix")
        notes = {q.stem.lower(): q for q in ctx.h.rglob("*.md")}
        for q in ctx.h.rglob("*.md"):
            if ctx.wiki in q.parents or ctx.compiled_generic in q.parents:
                continue
            for link in re.findall(r"\[\[([^\]|#]+)(?:[#|][^\]]*)?\]\]", q.read_text(encoding="utf-8")):
                target = link.strip().lower()
                if target and target not in notes and target not in lib:
                    warnings.append(f"{os.path.relpath(q, ctx.project)}: wikilink [[{link}]] has no note")
        for t in TARGETS:
            d = ctx.compiled_dir(t)
            if d.is_dir():
                for c in d.glob("*.md"):
                    if GENERATED_MARK in c.read_text(encoding="utf-8")[:2000] and c.stem not in inst:
                        warnings.append(f"{os.path.relpath(c, ctx.project)}: generated but no instance note; compile removes it")
    for e in errors:
        print(f"error    {e}")
    for w in warnings:
        print(f"warning  {w}")
    print(f"lint: {len(errors)} error(s), {len(warnings)} warning(s)")
    return 1 if errors else 0


# ----------------------------------------------------------------------------
# background bookkeeping
# ----------------------------------------------------------------------------

def cmd_ran(ctx: Ctx, args) -> int:
    if not ctx.index_note.exists():
        print("no harness/Harness.md; run init first", file=sys.stderr)
        return 1
    fm, body = read_note(ctx.index_note)
    fm[f"{args.agent}_last_run"] = today()
    fm["updated"] = today()
    write_note(ctx.index_note, fm, body)
    print(f"{args.agent} last run: {today()}")
    return 0


