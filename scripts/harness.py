def archive_note(src: Path, archive_dir: Path, did: str) -> Path:
    archive_dir.mkdir(parents=True, exist_ok=True)
    fm, body = read_note(src)
    fm["status"] = "archived"
    fm["archived_by"] = did
    fm["archived_on"] = today()
    dest = archive_dir / src.name
    k = 2
    while dest.exists():
        dest = archive_dir / f"{src.stem}.{k}.md"
        k += 1
    write_note(dest, fm, body)
    src.unlink()
    return dest


def restore_note(archived: Path, target_dir: Path) -> Path:
    fm, body = read_note(archived)
    fm["status"] = "active" if fm.get("type") == "agent-instance" else (fm.get("restored_status") or "proven")
    fm.pop("archived_by", None)
    fm.pop("archived_on", None)
    name = str(fm.get("name") or archived.stem.split(".")[0])
    dest = target_dir / f"{name}.md"
    if dest.exists():
        raise SystemExit(f"cannot restore {name}: {dest} exists")
    write_note(dest, fm, body)
    archived.unlink()
    return dest


def scope_dirs(ctx: Ctx, use_library: bool):
    if use_library:
        return LIB_AGENTS, LIB_ARCHIVE, LIB_DECISIONS, "L", LIB_INDEX
    return ctx.agents, ctx.archive, ctx.decisions, "H", ctx.index_note


def policy_gate(ctx: Ctx, names: list[str], use_library: bool, approved: bool, action: str) -> dict | None:
    lib = library_agents()
    items = pool(ctx, use_library)
    effs = []
    for n in names:
        if n not in items:
            raise SystemExit(f"not found: {n}")
        e = effective(items[n][1], lib)
        e["name"] = n
        effs.append(e)
    res = risk_assess(effs[0], effs[1] if len(effs) > 1 else None)
    for x in effs[2:]:
        r2 = risk_assess(effs[0], x)
        res["signals"] += r2["signals"]
        if r2["decision"] == "ask" and res["decision"] == "auto":
            res["decision"] = "ask"
        if r2["decision"] == "never":
            res["decision"] = "never"
    if res["decision"] == "never":
        raise SystemExit(f"{action} refused: a tier-0 agent is never merged, split or retired")
    if res["decision"] == "ask" and not approved:
        return res
    return None


