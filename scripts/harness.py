def bump_record(fm: dict, outcome: str, project_name: str | None = None) -> None:
    fm["tasks"] = as_int(fm.get("tasks")) + 1
    fm["successes"] = as_int(fm.get("successes")) + (1 if outcome == "ok" else 0)
    fm["last_used"] = today()
    if project_name is not None:
        used = as_list(fm.get("used_in"))
        if project_name not in used:
            used.append(project_name)
        fm["used_in"] = used


def cmd_ledger(ctx: Ctx, args) -> int:
    if args.ledger_cmd != "add":
        print("usage: ledger add ...", file=sys.stderr)
        return 1
    if not ctx.ledger.exists():
        print("no harness/ledger.md; run init first", file=sys.stderr)
        return 1
    outcome = args.outcome
    task = args.task.replace("|", "/").replace("\n", " ").strip()
    note = (args.note or "").replace("|", "/").replace("\n", " ").strip()
    row = f"| {today()} | {args.agent} | {args.model or ''} | {task} | {outcome} | {args.tokens or ''} | {note} |\n"
    with ctx.ledger.open("a", encoding="utf-8") as f:
        f.write(row)
    inst = ctx.instances()
    if args.agent in inst:
        p, fm, body = inst[args.agent]
        bump_record(fm, outcome)
        write_note(p, fm, body)
        libname = fm.get("library") or ""
        lib = library_agents()
        if libname in lib:
            lp, lfm, lbody = lib[libname]
            bump_record(lfm, outcome, ctx.name)
            write_note(lp, lfm, lbody)
    print(f"ledger: {args.agent} · {outcome} · {task}")
    return 0


