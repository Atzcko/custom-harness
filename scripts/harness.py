def cmd_init(ctx: Ctx, args) -> int:
    created, skipped = [], []
    mapping = {"project": ctx.name, "project_path": str(ctx.project), "date": today(),
               "skill_version": skill_version()}
    for d in [ctx.agents, ctx.archive, ctx.decisions, ctx.compiled_generic, ctx.wiki / "raw",
              ctx.wiki / "wiki" / "sources", ctx.wiki / "wiki" / "domains",
              ctx.wiki / "wiki" / "concepts", ctx.wiki / "wiki" / "synthesis"]:
        d.mkdir(parents=True, exist_ok=True)
    targets = choose_targets(ctx.project, args.target)
    wiki_stub = (f"# {ctx.name} harness wiki\n\nThis directory is an LLM-maintained wiki (the llm-wiki pattern). "
                 "Read `SCHEMA.md` in this directory before touching anything here; it is the schema and it wins "
                 "over any general instruction.\n")
    files = {
        ctx.index_note: fill(load_template("harness-index.md"), mapping),
        ctx.brief: fill(load_template("brief.md"), mapping),
        ctx.architecture: fill(load_template("architecture.md"), mapping),
        ctx.ledger: fill(load_template("ledger.md"), mapping),
        ctx.evolution: fill(load_template("evolution.md"), mapping),
        ctx.wiki / "SCHEMA.md": fill(load_template("wiki-schema.md"), mapping),
        ctx.wiki / "wiki" / "index.md": "# Index\n\n## Sources\n\n## Domains\n\n## Concepts\n\n## Synthesis\n",
        ctx.wiki / "wiki" / "log.md": f"# Log\n\n## [{today()}] bootstrap | {ctx.name} harness wiki\n",
    }
    # each detected tool reads its own instruction file name inside the wiki, so the schema is found by all of them
    for t in targets:
        fname = INSTRUCTION_FILES.get(t)
        if fname:
            files[ctx.wiki / fname] = wiki_stub
    for path, content in files.items():
        if path.exists():
            skipped.append(path)
        else:
            path.write_text(content, encoding="utf-8")
            created.append(path)
    # pointer in every instruction file the detected tools read
    for t in targets:
        fname = INSTRUCTION_FILES.get(t)
        if not fname:
            continue
        f = ctx.project / fname
        if f.exists():
            text = f.read_text(encoding="utf-8")
            if POINTER_START in text:
                skipped.append(f)
                continue
            f.write_text(text.rstrip("\n") + "\n\n" + pointer_block(), encoding="utf-8")
        else:
            f.write_text(f"# {ctx.name}\n\n" + pointer_block(), encoding="utf-8")
        created.append(f)
    rel = lambda p: os.path.relpath(p, ctx.project)
    print(f"harness init - {ctx.name} (targets: {', '.join(targets)})")
    for p in created:
        print(f"  created  {rel(p)}")
    for p in skipped:
        print(f"  kept     {rel(p)}")
    print("next: understand the project (references/understand.md); the brief is at harness/brief.md")
    return 0


