def link_claude_memory(name: str, memdir: Path) -> str:
    """Point Claude Code's per-agent memory directory at the library copy."""
    root = HOME / ".claude" / "agent-memory"
    link = root / name
    try:
        root.mkdir(parents=True, exist_ok=True)
        if link.is_symlink():
            if link.resolve() == memdir.resolve():
                return "linked"
            link.unlink()
            link.symlink_to(memdir, target_is_directory=True)
            return "relinked"
        if link.exists():
            return f"left alone: {link} is a real directory; merge it into {memdir} by hand"
        link.symlink_to(memdir, target_is_directory=True)
        return "linked"
    except OSError as e:
        return f"could not link: {e}"


def tools_line(tools: list[str], spawns) -> tuple[str | None, str | None]:
    tools = [str(t) for t in tools if str(t).strip() and str(t) != "Agent" and not str(t).startswith("Agent(")]
    sp = as_list(spawns)
    if sp == ["*"]:
        return ((", ".join(tools + ["Agent"])) if tools else None), None
    if sp:
        base = tools or list(DEFAULT_TOOLS)
        return ", ".join(base + [f"Agent({', '.join(str(s) for s in sp)})"]), None
    return ((", ".join(tools)) if tools else None), "Agent"


