def as_list(v) -> list:
    if v is None or v == "":
        return []
    if isinstance(v, list):
        return [x for x in v if x != ""]
    return [v]


def as_int(v, default=0) -> int:
    try:
        return int(v)
    except Exception:
        return default


def fill(template: str, mapping: dict) -> str:
    out = template
    for k, v in mapping.items():
        out = out.replace("{{" + k + "}}", str(v))
    return out


def load_template(name: str) -> str:
    return (TEMPLATES / name).read_text(encoding="utf-8")


def tokenize(text: str) -> set[str]:
    toks = set()
    for w in re.findall(r"[a-z0-9]+", (text or "").lower()):
        if len(w) < 3 or w in STOPWORDS:
            continue
        if w.endswith("ies") and len(w) > 4:
            w = w[:-3] + "y"
        elif w.endswith("ing") and len(w) > 5:
            w = w[:-3]
        elif w.endswith("ed") and len(w) > 4:
            w = w[:-2]
        elif w.endswith("s") and not w.endswith("ss") and len(w) > 3:
            w = w[:-1]
        toks.add(w)
    return toks


def jaccard(a: set, b: set) -> float:
    if not a and not b:
        return 0.0
    return len(a & b) / len(a | b)


def norm_tags(v) -> set[str]:
    return {str(t).strip().lower() for t in as_list(v) if str(t).strip()}


def slug_ok(name: str) -> bool:
    return re.fullmatch(r"[a-z0-9][a-z0-9\-]*", name or "") is not None


def line_hash(s: str) -> str:
    return hashlib.sha1(re.sub(r"\s+", " ", s.strip().lower()).encode()).hexdigest()[:12]


