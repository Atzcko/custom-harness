def cmd_promote(ctx: Ctx, args) -> int:
    inst = ctx.instances()
    if args.name not in inst:
        print(f"not found in project: {args.name}", file=sys.stderr)
        return 1
    p, fm, body = inst[args.name]
    if fm.get("library"):
        print(f"{args.name} is already linked to library agent `{fm['library']}`", file=sys.stderr)
        return 1
    libname = args.as_name or args.name
    if not slug_ok(libname):
        print("library name must be lowercase letters, digits and hyphens", file=sys.stderr)
        return 1
    if (LIB_AGENTS / f"{libname}.md").exists():
        print(f"library agent exists: {libname}", file=sys.stderr)
        return 1
    tasks, ok = as_int(fm.get("tasks")), as_int(fm.get("successes"))
    proven = tasks >= 5 and ok / tasks >= 0.8
    if not proven and not args.force:
        print(f"{args.name} has {tasks} tasks, {ok} successful; promotion needs 5 tasks with 4 in 5 successful (or --force)", file=sys.stderr)
        return 1
    charter = get_section(body, "Charter")
    text = fill(load_template("agent.md"), {"name": libname, "title": fm.get("title", libname), "tier": fm.get("tier", 2),
                                            "model": fm.get("model", ""), "description": fm.get("description", ""),
                                            "tags": ", ".join(str(t) for t in as_list(fm.get("tags"))),
                                            "project": ctx.name, "date": today()})
    lfm, lbody = parse_frontmatter(text)
    lfm.update({"tools": as_list(fm.get("tools")), "skills": as_list(fm.get("skills")), "spawns": as_list(fm.get("spawns")),
                "danger": as_list(fm.get("danger")), "irreversible": bool(fm.get("irreversible")),
                "status": "proven" if proven else "draft", "used_in": [ctx.name], "tasks": tasks, "successes": ok,
                "last_used": fm.get("last_used", "")})
    lbody = f"\n# {fm.get('title', libname)}\n\n## Charter\n\n{charter or '(write the charter)'}\n\n## Inputs and outputs\n\n(fill in)\n\n## How you judge done\n\n(fill in)\n\n## Boundaries\n\n(fill in)\n"
    write_note(LIB_AGENTS / f"{libname}.md", lfm, lbody)
    if libname != args.name and (LIB_MEMORY / args.name).is_dir() and not (LIB_MEMORY / libname).exists():
        shutil.move(str(LIB_MEMORY / args.name), str(LIB_MEMORY / libname))
    fm["library"] = libname
    fm["library_version"] = 1
    fm["status"] = "active"
    body = set_section(body, "Charter", "Inherited from the library at compile time. Leave empty for a linked agent.")
    body = append_to_section(body, "Project memory", f"- {today()} — promoted to the library as `{libname}` ({'proven' if proven else 'draft'}).")
    write_note(p, fm, body)
    cmd_index(ctx, args)
    cmd_compile(ctx, args)
    print(f"promoted {args.name} -> library/agents/{libname}.md ({'proven' if proven else 'draft'}); "
          "read the charter and strip what only made sense in this project")
    return 0


