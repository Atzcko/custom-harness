def ledger_rows(ctx: Ctx) -> list[dict]:
    rows = []
    if not ctx.ledger.exists():
        return rows
    for line in ctx.ledger.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|") or line.startswith("|---") or line.startswith("| date"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 5:
            continue
        rows.append({"date": cells[0], "agent": cells[1], "model": cells[2], "task": cells[3],
                     "outcome": cells[4], "tokens": cells[5] if len(cells) > 5 else "",
                     "note": cells[6] if len(cells) > 6 else ""})
    return rows


def uncollected_lessons(ctx: Ctx) -> list[str]:
    if not ctx.evolution.exists():
        return []
    known = set()
    if LESSONS.exists():
        for line in LESSONS.read_text(encoding="utf-8").splitlines():
            m = re.match(r"^- \[[ x]\] (\S+) · (.+?) · (.+)$", line)
            if m:
                known.add(line_hash(m.group(3)))
    out = []
    for line in ctx.evolution.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^- (\d{4}-\d{2}-\d{2}) [—-]+ (.+)$", line)
        if not m:
            continue
        text = m.group(2).strip()
        if "harness initialised" in text:
            continue
        if line_hash(text) not in known:
            out.append(f"{m.group(1)} · {text}")
    return out


def compute_phase(ctx: Ctx) -> tuple[str, str]:
    if not ctx.exists():
        return "understand", "no harness/ folder; run init"
    brief_ready = False
    if ctx.brief.exists():
        fm, _ = read_note(ctx.brief)
        brief_ready = str(fm.get("status", "")).lower() == "ready"
    if not brief_ready:
        return "understand", "harness/brief.md is not marked ready"
    inst = ctx.active_instances()
    if not ctx.architecture.exists() or not inst:
        return "architect", "no architecture or no agents yet"
    compiled = {p.stem for p in ctx.compiled_generic.glob("*.md")} if ctx.compiled_generic.is_dir() else set()
    missing = [n for n in inst if n not in compiled]
    if missing:
        return "architect", f"agents not compiled: {', '.join(missing)}"
    return "operate", "roster compiled"


