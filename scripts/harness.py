def cmd_compile(ctx: Ctx, args) -> int:
    if not ctx.exists():
        print("no harness/ folder; run init first", file=sys.stderr)
        return 1
    lib = library_agents()
    reg = load_models()
    targets = choose_targets(ctx.project, args.target)
    inst = ctx.instances()
    written: dict[str, list[str]] = {t: [] for t in targets}
    removed: list[str] = []
    notes: list[str] = []
    specs: list[dict] = []
    for name, (p, fm, body) in inst.items():
        if fm.get("status") not in ("active", "draft"):
            continue
        if not slug_ok(name):
            print(f"skip {name}: not a valid agent name", file=sys.stderr)
            continue
        spec = build_spec(ctx, name, p, fm, body, lib, reg, targets)
        specs.append(spec)
        for t in targets:
            outputs = RENDERERS[t](spec, ctx)
            if t == "claude":
                state = link_claude_memory(name, Path(spec["memory_dir"]))
                if state not in ("linked", "relinked"):
                    notes.append(f"{name}: memory {state}")
            for path, text in outputs:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
            written[t].append(name)
        libname = spec["library"]
        fm["compiled_from"] = f"{libname}@{spec['library_version']}" if libname else "local"
        if libname:
            fm["library_version"] = spec["library_version"]
        write_note(p, fm, body)
        for t in targets:
            for suffix in (".md", ".json", ".toml"):
                cp = ctx.compiled_dir(t) / f"{name}{suffix}"
                if cp.exists():
                    os.utime(cp, None)
    active = {s["name"] for s in specs}
    for t in targets:
        d = ctx.compiled_dir(t)
        if not d.is_dir():
            continue
        for p in list(d.glob("*.md")) + list(d.glob("*.json")) + list(d.glob("*.toml")):
            if p.stem in active:
                continue
            head = p.read_text(encoding="utf-8")[:2000]
            if GENERATED_MARK in head or (p.suffix == ".json" and '"instance_note"' in head):
                p.unlink()
                removed.append(f"{t}/{p.name}")
    for f in render_instruction_blocks(ctx, targets, specs):
        notes.append(f"roster table written to {f.name}")
    print(f"compiled {len(specs)} agent(s) for {', '.join(targets)}: {', '.join(s['name'] for s in specs) or '-'}")
    for n in notes:
        print(f"  {n}")
    if removed:
        print(f"removed generated files with no active instance: {', '.join(removed)}")
    return 0


