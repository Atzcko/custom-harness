def get_section(body: str, heading: str) -> str:
    m = re.search(rf"^## {re.escape(heading)}\s*$", body, flags=re.M)
    if not m:
        return ""
    rest = body[m.end():]
    n = re.search(r"^## ", rest, flags=re.M)
    return (rest[: n.start()] if n else rest).strip("\n").rstrip()


def set_section(body: str, heading: str, content: str) -> str:
    m = re.search(rf"^## {re.escape(heading)}\s*$", body, flags=re.M)
    block = f"## {heading}\n\n{content.strip()}\n"
    if not m:
        return body.rstrip("\n") + "\n\n" + block
    rest = body[m.end():]
    n = re.search(r"^## ", rest, flags=re.M)
    tail = rest[n.start():] if n else ""
    return body[: m.start()] + block + ("\n" + tail if tail else "")


def append_to_section(body: str, heading: str, line: str) -> str:
    cur = get_section(body, heading)
    new = (cur + "\n" if cur else "") + line
    return set_section(body, heading, new)


def h1_title(body: str, default: str) -> str:
    m = re.search(r"^# (.+)$", body, flags=re.M)
    return m.group(1).strip() if m else default


def strip_h1(body: str) -> str:
    return re.sub(r"^# .+\n", "", body.lstrip("\n"), count=1)


def replace_block(text: str, start: str, end: str, block: str) -> str:
    """Replace or append a marked block in an instruction file."""
    if start in text and end in text:
        pre = text[: text.index(start)]
        post = text[text.index(end) + len(end):]
        return pre.rstrip("\n") + "\n\n" + block.strip("\n") + "\n" + post
    return text.rstrip("\n") + "\n\n" + block.strip("\n") + "\n"


