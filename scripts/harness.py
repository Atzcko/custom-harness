def pool(ctx: Ctx, use_library: bool) -> dict[str, tuple[Path, dict, str]]:
    if use_library:
        return library_agents()
    return ctx.active_instances()


def effective(fm: dict, lib: dict) -> dict:
    libname = fm.get("library") or ""
    libfm = lib[libname][1] if libname in lib else {}
    out = dict(libfm)
    for k, v in fm.items():
        if v not in ("", [], None):
            out[k] = v
    out["tags"] = sorted(norm_tags(fm.get("tags")) | norm_tags(libfm.get("tags")))
    out["danger"] = as_list(fm.get("danger")) or as_list(libfm.get("danger"))
    out["irreversible"] = bool(fm.get("irreversible")) or bool(libfm.get("irreversible"))
    out["tasks"] = max(as_int(fm.get("tasks")), as_int(libfm.get("tasks")))
    out["used_in"] = as_list(libfm.get("used_in"))
    out["tier"] = as_int(fm.get("tier") if fm.get("tier") != "" else libfm.get("tier", 2), 2)
    out["model"] = str(fm.get("model") or libfm.get("model") or "")
    return out


def pair_similarity(a: dict, b: dict) -> dict:
    ta, tb = set(a.get("tags", [])), set(b.get("tags", []))
    da = tokenize(f"{a.get('title','')} {a.get('description','')}")
    db = tokenize(f"{b.get('title','')} {b.get('description','')}")
    oa, ob = {str(t) for t in as_list(a.get("tools"))}, {str(t) for t in as_list(b.get("tools"))}
    tag_j, desc_j = jaccard(ta, tb), jaccard(da, db)
    tool_j = jaccard(oa, ob) if oa and ob else 0.0
    sim = 0.5 * tag_j + 0.4 * desc_j + 0.1 * tool_j
    return {"sim": round(sim, 2), "tags": round(tag_j, 2), "desc": round(desc_j, 2), "tools": round(tool_j, 2)}


def cmd_overlap(ctx: Ctx, args) -> int:
    lib = library_agents()
    items = pool(ctx, args.library)
    if not items:
        print("nothing to compare")
        return 0
    eff = {n: effective(fm, lib) for n, (p, fm, body) in items.items()}
    names = sorted(eff)
    merges, splits = [], []
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            s = pair_similarity(eff[a], eff[b])
            if s["sim"] >= args.threshold:
                merges.append({"a": a, "b": b, **s})
    for n in names:
        tags = eff[n].get("tags", [])
        if len(tags) >= args.broad:
            splits.append({"name": n, "reason": f"{len(tags)} tags"})
    merges.sort(key=lambda r: r["sim"], reverse=True)
    if args.json:
        print(json.dumps({"scope": "library" if args.library else "project", "merge_candidates": merges,
                          "split_candidates": splits}, indent=2))
        return 0
    scope = "library" if args.library else ctx.name
    print(f"overlap - {scope} ({len(names)} agents, threshold {args.threshold})")
    if merges:
        print("merge candidates:")
        for r in merges:
            print(f"  {r['sim']:.2f}  {r['a']} + {r['b']}   (tags {r['tags']:.2f}, description {r['desc']:.2f}, tools {r['tools']:.2f})")
    else:
        print("merge candidates: none")
    if splits:
        print("split candidates:")
        for r in splits:
            print(f"  {r['name']}: {r['reason']}")
    else:
        print("split candidates: none")
    return 0


def risk_assess(a: dict, b: dict | None) -> dict:
    agents = [a] + ([b] if b else [])
    tier = min(x["tier"] for x in agents)
    signals = []
    for x in agents:
        nm = x.get("name", "?")
        if x.get("danger"):
            signals.append(f"{nm}: danger flags {', '.join(str(d) for d in x['danger'])}")
        if x.get("irreversible"):
            signals.append(f"{nm}: irreversible actions allowed")
        if len(x.get("used_in", [])) >= 2:
            signals.append(f"{nm}: used by {len(x['used_in'])} projects")
        if x.get("tasks", 0) >= 20:
            signals.append(f"{nm}: track record of {x['tasks']} tasks")
    if tier == 0:
        decision = "never"
    elif tier <= 1 and signals:
        decision = "ask"
    else:
        decision = "auto"
    return {"decision": decision, "altitude": "high" if tier <= 1 else "low", "tier": tier, "signals": signals}


def cmd_risk(ctx: Ctx, args) -> int:
    lib = library_agents()
    items = pool(ctx, args.library)
    for n in [args.a] + ([args.b] if args.b else []):
        if n not in items:
            print(f"not found in {'library' if args.library else 'project'}: {n}", file=sys.stderr)
            return 1
    a = effective(items[args.a][1], lib)
    a["name"] = args.a
    b = None
    if args.b:
        b = effective(items[args.b][1], lib)
        b["name"] = args.b
    print(json.dumps(risk_assess(a, b), indent=2))
    return 0


