def obsidian_installed() -> str:
    for p in (Path("/Applications/Obsidian.app"), HOME / "Applications" / "Obsidian.app"):
        if p.exists():
            return str(p)
    w = shutil.which("obsidian")
    return w or ""


def bundle_state(name: str, installed: list[Path]) -> str:
    b = BUNDLED / name
    if not b.is_dir():
        return "no bundled copy"
    if not installed:
        return "bundled copy will be used"
    inst = installed[0]
    diffs = []
    for f in sorted(b.rglob("*.md")):
        rel = f.relative_to(b)
        g = inst / rel
        if not g.exists() or g.read_text(encoding="utf-8") != f.read_text(encoding="utf-8"):
            diffs.append(str(rel))
    if not diffs:
        return "bundled copy identical to installed"
    newer = "installed" if max(g.stat().st_mtime for g in inst.rglob("*.md")) > max(f.stat().st_mtime for f in b.rglob("*.md")) else "bundled"
    return f"bundled copy differs in {', '.join(diffs)}; {newer} is newer"


def cmd_doctor(ctx: Ctx, args) -> int:
    rows: list[tuple[str, str, str]] = []
    hard_missing = []
    py = f"{platform.python_version()} at {sys.executable}"
    rows.append(("python3", "ok", py))
    uvp = shutil.which("uv")
    rows.append(("uv", "ok" if uvp else "missing", uvp or "optional; runs the skill validator with PyYAML"))
    gb = shutil.which("graphify")
    rows.append(("graphify binary", "ok" if gb else "missing", gb or "the graphify skill installs it on first use"))
    ob = obsidian_installed()
    rows.append(("obsidian app", "ok" if ob else "missing", ob or "optional; the vault still works as plain markdown"))
    for name in REQUIRED_SKILLS:
        found = find_skill(name, ctx.project)
        where = ", ".join(str(p).replace(str(HOME), "~") for p in found)
        if found:
            note = where
            if name == "llm-wiki":
                note += f" ({bundle_state(name, found)})"
            rows.append((f"skill {name}", "ok", note))
        elif name == "llm-wiki" and (BUNDLED / "llm-wiki" / "SKILL.md").exists():
            rows.append((f"skill {name}", "bundled", f"not installed; using {str(BUNDLED / 'llm-wiki').replace(str(HOME), '~')}"))
        else:
            rows.append((f"skill {name}", "missing", "install it into ~/.agents/skills or ~/.claude/skills"))
            hard_missing.append(name)
    launcher = shutil.which("harness")
    rows.append(("harness launcher", "ok" if launcher else "missing", launcher or "run ./install.sh; prompts fall back to the python path"))
    installed_in = [str(r / "harness").replace(str(HOME), "~") for r in SKILL_ROOTS if (r / "harness" / "SKILL.md").exists()]
    rows.append(("skill installed in", "ok" if installed_in else "missing", ", ".join(installed_in) or "run ./install.sh"))
    det = detect_targets(ctx.project)
    rows.append(("targets", "ok" if det else "none", ", ".join(f"{t} ({w})" for t, w in det.items()) or "no tool directories found; generic only"))
    reg = load_models()
    age = registry_age_days(reg)
    maxage = as_int(reg.get("max_age_days"), 14)
    if age is None:
        rows.append(("model registry", "missing", "library/models.json has no checked date; run `harness models set` / `touch`"))
    else:
        rows.append(("model registry", "ok" if age <= maxage else "stale", f"checked {reg.get('checked')} ({age} days old, max {maxage})"))
    for t in det:
        prov = provider_for(t, reg)
        if prov not in (reg.get("providers") or {}):
            rows.append((f"models for {t}", "missing", f"no provider entry `{prov}`; add one with `harness models set --provider {prov} ...`"))
    if args.json:
        print(json.dumps([{"check": a, "state": b, "detail": c} for a, b, c in rows], indent=2))
    else:
        w = max(len(r[0]) for r in rows)
        print(f"harness doctor - {ctx.name}")
