# ----------------------------------------------------------------------------
# frontmatter (a small YAML subset: scalars, inline lists, block lists, folded)
# ----------------------------------------------------------------------------

def _split_commas(s: str) -> list[str]:
    out, cur, quote = [], "", None
    for ch in s:
        if quote:
            cur += ch
            if ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
            cur += ch
        elif ch == ",":
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return out


def parse_scalar(raw: str):
    s = raw.strip()
    if s == "" or s in ("null", "~"):
        return ""
    if len(s) >= 2 and s[0] == '"' and s[-1] == '"':
        try:
            return json.loads(s)
        except Exception:
            return s[1:-1]
    if len(s) >= 2 and s[0] == "'" and s[-1] == "'":
        return s[1:-1].replace("''", "'")
    if s == "true":
        return True
    if s == "false":
        return False
    if re.fullmatch(r"-?\d+", s):
        return int(s)
    return s


def parse_frontmatter(text: str):
    if not text.startswith("---"):
        return {}, text
    lines = text.split("\n")
    end = None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            end = i
            break
    if end is None:
        return {}, text
    fm = lines[1:end]
    body = "\n".join(lines[end + 1:])
    data: dict = {}
    i = 0
    while i < len(fm):
        line = fm[i]
        if not line.strip() or line.lstrip().startswith("#"):
            i += 1
            continue
        m = re.match(r"^([A-Za-z0-9_\-]+):(.*)$", line)
        if not m:
            i += 1
            continue
        key, rest = m.group(1), m.group(2).strip()
        if rest == "":
            items, j = [], i + 1
            while j < len(fm) and re.match(r"^\s+-(\s|$)", fm[j]):
                items.append(parse_scalar(fm[j].strip()[1:].strip()))
                j += 1
            if j > i + 1:
                data[key] = items
                i = j
                continue
            data[key] = ""
            i += 1
            continue
        if rest in (">", "|", ">-", "|-"):
            parts, j = [], i + 1
            while j < len(fm) and (fm[j].startswith("  ") or fm[j].strip() == ""):
                parts.append(fm[j].strip())
                j += 1
            sep = " " if rest.startswith(">") else "\n"
            data[key] = sep.join(p for p in parts if p).strip()
            i = j
            continue
        if rest.startswith("[") and rest.endswith("]"):
            inner = rest[1:-1].strip()
            data[key] = [parse_scalar(x) for x in _split_commas(inner)] if inner else []
            i += 1
            continue
        data[key] = parse_scalar(rest)
        i += 1
    return data, body


_NEEDS_QUOTE = re.compile(r"(: )|( #)|^[\[\]{}&*!|>'\"%@`,\-?]|^\s|\s$|^(true|false|null|yes|no|~)$|^-?\d+(\.\d+)?$|[:\n]$")


def dump_scalar(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    s = "" if v is None else str(v)
    if s == "":
        return ""
    if _NEEDS_QUOTE.search(s) or (":" in s and " " in s):
        return json.dumps(s, ensure_ascii=False)
    return s


def dump_frontmatter(data: dict) -> str:
    out = ["---"]
    for k, v in data.items():
        if isinstance(v, list):
            out.append(f"{k}: [{', '.join(dump_scalar(x) for x in v)}]")
        else:
            sv = dump_scalar(v)
            out.append(f"{k}: {sv}" if sv != "" else f"{k}:")
    out.append("---")
    return "\n".join(out) + "\n"


def read_note(path: Path):
    text = path.read_text(encoding="utf-8")
    return parse_frontmatter(text)


def write_note(path: Path, fm: dict, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not body.startswith("\n"):
        body = "\n" + body
    path.write_text(dump_frontmatter(fm) + body.rstrip("\n") + "\n", encoding="utf-8")


