def match_scores(query: str, tags: list[str], target: str, reg: dict) -> list[dict]:
    q = tokenize(query)
    qt = {t.lower() for t in tags}
    out = []
    for name, (p, fm, body) in library_agents().items():
        atags = norm_tags(fm.get("tags"))
        d = tokenize(f"{fm.get('title','')} {fm.get('description','')} {' '.join(atags)}")
        desc_sim = len(q & d) / len(q) if q else 0.0
        if qt:
            tag_sim = len(qt & atags) / len(qt)
        else:
            tag_sim = len(q & atags) / max(1, min(len(q), len(atags))) if atags else 0.0
        status = fm.get("status", "")
        bonus = {"proven": 0.10, "seed": 0.05}.get(status, 0.0) + min(as_int(fm.get("tasks")), 20) / 20 * 0.05
        score = min(1.0, 0.55 * desc_sim + 0.35 * tag_sim + bonus)
        band = "reuse" if score >= 0.60 else ("adapt" if score >= 0.35 else "create")
        tier = as_int(fm.get("tier"), 2)
        out.append({"name": name, "score": round(score, 2), "band": band, "tier": tier,
                    "model": resolve_model(target, tier, [str(fm.get("model") or "")], reg), "status": status,
                    "desc_sim": round(desc_sim, 2), "tag_sim": round(tag_sim, 2),
                    "description": str(fm.get("description", ""))})
    out.sort(key=lambda r: r["score"], reverse=True)
    return out


def cmd_match(ctx: Ctx, args) -> int:
    tags = [t for t in (args.tags or "").split(",") if t.strip()]
    reg = load_models()
    target = choose_targets(ctx.project, args.target)[0]
    res = match_scores(args.query, tags, target, reg)
    top = res[: args.top]
    if args.json:
        print(json.dumps(top, indent=2))
        return 0
    print(f"match: {args.query!r}" + (f"  tags={tags}" if tags else "") + f"  (models shown for {target})")
    if not top:
        print("  library is empty")
        return 0
    for r in top:
        print(f"  {r['score']:.2f}  {r['band']:<6} {r['name']:<14} tier {r['tier']} {r['model']:<14} {r['status']:<6} "
              f"desc {r['desc_sim']:.2f} tags {r['tag_sim']:.2f}")
    best = top[0]
    if best["band"] == "reuse":
        print(f"suggestion: reuse `{best['name']}` as is (link it; project context only)")
    elif best["band"] == "adapt":
        print(f"suggestion: adapt `{best['name']}` with an overlay (link it; add context, tools or a pinned model)")
    else:
        print("suggestion: create a local draft; nothing in the library is close enough")
    return 0


