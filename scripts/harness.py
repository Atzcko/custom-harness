def load_models() -> dict:
    if MODELS_FILE.exists():
        try:
            reg = json.loads(MODELS_FILE.read_text(encoding="utf-8"))
            if isinstance(reg, dict) and "providers" in reg:
                return reg
        except Exception:
            pass
    return json.loads(json.dumps(DEFAULT_MODELS))


def save_models(reg: dict) -> None:
    MODELS_FILE.parent.mkdir(parents=True, exist_ok=True)
    MODELS_FILE.write_text(json.dumps(reg, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def registry_age_days(reg: dict) -> int | None:
    try:
        d = _dt.date.fromisoformat(str(reg.get("checked", "")))
    except Exception:
        return None
    return (_dt.date.today() - d).days


def target_entry(target: str, reg: dict) -> tuple[str, str]:
    """(provider, id prefix) for a target; targets may be a provider name or an object."""
    e = (reg.get("targets") or {}).get(target)
    if isinstance(e, dict):
        return str(e.get("provider") or "anthropic"), str(e.get("prefix") or "")
    return str(e or "anthropic"), ""


def provider_for(target: str, reg: dict) -> str:
    return target_entry(target, reg)[0]


def resolve_model(target: str, tier: int, pins: list[str], reg: dict) -> str:
    for p in pins:
        if p:
            return str(p)
    prov, prefix = target_entry(target, reg)
    tiers = ((reg.get("providers") or {}).get(prov) or {}).get("tiers") or {}
    m = tiers.get(str(tier))
    if not m:
        # fall back to the nearest cheaper tier, then anything
        for t in list(range(tier, 4)) + list(range(tier, -1, -1)):
            if tiers.get(str(t)):
                m = tiers[str(t)]
                break
    if not m:
        return ""
    m = str(m)
    return m if (not prefix or m.startswith(prefix)) else prefix + m


def alias_rank(model: str) -> int:
    m = (model or "").lower()
    for alias, r in ALIAS_RANK.items():
        if alias in m:
            return r
    return 0


def most_capable_pin(models: list[str]) -> str:
    pins = [m for m in models if m]
    if not pins:
        return ""
    return max(pins, key=alias_rank)


