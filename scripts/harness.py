class Ctx:
    def __init__(self, project: str | None):
        self.project = Path(project or os.getcwd()).resolve()
        self.name = self.project.name
        self.h = self.project / "harness"
        self.agents = self.h / "agents"
        self.archive = self.agents / "_archive"
        self.decisions = self.h / "decisions"
        self.compiled_generic = self.h / "compiled"
        self.compiled = self.project / ".claude" / "agents"
        self.index_note = self.h / "Harness.md"
        self.brief = self.h / "brief.md"
        self.architecture = self.h / "architecture.md"
        self.ledger = self.h / "ledger.md"
        self.evolution = self.h / "evolution.md"
        self.wiki = self.h / "wiki"

    def exists(self) -> bool:
        return self.h.is_dir()

    def instances(self) -> dict[str, tuple[Path, dict, str]]:
        out = {}
        if not self.agents.is_dir():
            return out
        for p in sorted(self.agents.glob("*.md")):
            fm, body = read_note(p)
            if fm.get("type") != "agent-instance":
                continue
            out[str(fm.get("name") or p.stem)] = (p, fm, body)
        return out

    def active_instances(self):
        return {k: v for k, v in self.instances().items() if v[1].get("status") in ("active", "draft")}

    def compiled_dir(self, target: str) -> Path:
        return {"claude": self.project / ".claude" / "agents", "codex": self.project / ".codex" / "agents",
                "gemini": self.project / ".gemini" / "agents", "cursor": self.project / ".cursor" / "agents",
                "opencode": self.project / ".opencode" / "agents", "generic": self.compiled_generic}[target]


def library_agents(include_retired: bool = False) -> dict[str, tuple[Path, dict, str]]:
    out = {}
    if not LIB_AGENTS.is_dir():
        return out
    for p in sorted(LIB_AGENTS.glob("*.md")):
        fm, body = read_note(p)
        if fm.get("type") != "agent":
            continue
        if not include_retired and fm.get("status") == "retired":
            continue
        out[str(fm.get("name") or p.stem)] = (p, fm, body)
    return out


def next_decision_id(folder: Path, prefix: str) -> str:
    n = 0
    if folder.is_dir():
        for p in folder.glob(f"{prefix}*.md"):
            m = re.match(rf"{prefix}(\d+)", p.name)
            if m:
                n = max(n, int(m.group(1)))
    return f"{prefix}{n + 1:03d}"


def write_decision(folder: Path, prefix: str, title: str, by: str, status: str,
                   context: str, decision: str, consequences: str, undo: str,
                   related: str, extra: dict | None = None) -> tuple[str, Path]:
    did = next_decision_id(folder, prefix)
    text = fill(load_template("decision.md"), {
        "id": did, "title": title, "date": today(), "status": status, "by": by,
        "context": context, "decision": decision, "consequences": consequences,
        "undo": undo, "related": related or "-",
    })
    fm, body = parse_frontmatter(text)
    fm.update(extra or {})
    path = folder / f"{did} - {title}.md"
    write_note(path, fm, body)
    return did, path


def add_index_row(note: Path, did: str, title: str, claim: str) -> None:
    if not note.exists():
        return
    fm, body = read_note(note)
    row = f"| [[{did} - {title}]] | {claim} |"
    if "## Decisions" in body:
        body = append_to_section(body, "Decisions", row)
    else:
        body = body.rstrip("\n") + f"\n\n## Decisions\n\n| Decision | Claim |\n|---|---|\n{row}\n"
    fm["updated"] = today()
    write_note(note, fm, body)


