def cmd_undo(ctx: Ctx, args) -> int:
    did = args.decision
    use_library = did.upper().startswith("L")
    agents_dir, archive_dir, dec_dir, prefix, index_note = scope_dirs(ctx, use_library)
    matches = list(dec_dir.glob(f"{did} - *.md")) if dec_dir.is_dir() else []
    if not matches:
        print(f"decision not found: {did}", file=sys.stderr)
        return 1
    dpath = matches[0]
    fm, body = read_note(dpath)
    if fm.get("status") == "undone":
        print(f"{did} is already undone", file=sys.stderr)
        return 1
    if fm.get("status") == "proposed":
        fm["status"] = "rejected"
        write_note(dpath, fm, body)
        print(f"{did} was only proposed; marked rejected")
        return 0
    restore = as_list(fm.get("undo_restore"))
    to_archive = as_list(fm.get("undo_archive"))
    undo_id = f"{did}-undo"
    archived_now = []
    for name in to_archive:
        src = agents_dir / f"{name}.md"
        if src.exists():
            archived_now.append(archive_note(src, archive_dir, undo_id).name)
    restored = []
    for fname in restore:
        src = archive_dir / fname
        if not src.exists():
            print(f"missing archive file: {fname}", file=sys.stderr)
            continue
        restored.append(restore_note(src, agents_dir).name)
    fm["status"] = "undone"
    fm["undone_on"] = today()
    body = body.rstrip("\n") + f"\n\n## Undone\n\n{today()} — reversed with `harness undo {did}`. Restored: {', '.join(restored) or '-'}. Archived: {', '.join(archived_now) or '-'}.\n"
    write_note(dpath, fm, body)
    add_index_row(index_note, did, dpath.stem.split(" - ", 1)[1], f"undone on {today()}")
    print(f"undone {did}: restored {', '.join(restored) or '-'}; archived {', '.join(archived_now) or '-'}")
    if not use_library:
        cmd_compile(ctx, args)
    else:
        cmd_index(ctx, args)
    return 0


